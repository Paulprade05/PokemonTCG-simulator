/* ==================================================================== *
 * PRECIO DECRECIENTE POR NÚMERO DE COPIAS
 * ====================================================================
 *
 * SELL_PRICES es el precio de la PRIMERA copia repetida. A partir de ahí cada
 * copia adicional vale menos, hasta un suelo.
 *
 * POR QUÉ: con precio plano, quien exprime una expansión acumula miles de
 * repetidas y las vacía de una sentada. Medido con packLogic y las cartas
 * reales (apartado 3 de scripts/sim-economia.mjs): 3.000 sobres de sv3pt5 son
 * 150.000 monedas gastadas y dejan ~29.800 duplicados que a precio plano se
 * venden por ~143.600 — el 96% de lo gastado vuelve de golpe con un botón. Con
 * la curva son ~61.200, el 41%. Y quien completa la expansión entera pasa de
 * recuperar el 96% al 48%. Eso era una imprenta con un paso intermedio.
 *
 * LA CURVA (precio de la copia repetida nº n, como fracción de SELL_PRICES):
 *
 *     factor(n) = max(SUELO_COPIAS, 1 / (1 + (n - 1) / SEMIVIDA_COPIAS))
 *
 * Una hipérbola, no una exponencial: baja despacio en las primeras copias (que
 * es donde vive el jugador normal) y se aplana en vez de desplomarse a cero.
 * Con SEMIVIDA_COPIAS = 6 la copia nº 7 vale la mitad; con SUELO_COPIAS = 1/8
 * el suelo se toca EXACTAMENTE en la copia nº 43
 * (COPIA_SUELO = 1 + SEMIVIDA × (1/SUELO − 1)), y de ahí no baja más.
 *
 *   copia nº:   1     2     3     4     5     7    13    25    43+
 *   factor:   100%   86%   75%   67%   60%   50%   33%   20%   12,5%
 *
 * POR QUÉ SEMIVIDA 6 Y NO 4 (medido, apartado 1 de scripts/sim-economia.mjs):
 * el vaciado de una expansión completa está dominado por las comunes, que ya
 * tocan el mínimo de 1 moneda pase lo que pase, así que pasar de 4 a 6 sólo
 * sube el botín del acaparador del 38% al 41% de lo que era — pero al jugador
 * que tiene 4 copias de sus comunes le devuelve el 92% en vez del 81%. Se
 * frena al que farmea sin castigar al que juega, que es el criterio.
 *
 * POR QUÉ ESTE SUELO Y NO CERO: "tampoco muy bajo". Ninguna carta se regala
 * (mínimo 1 moneda) y las caras siguen valiendo dinero por la copia nº 50: una
 * Hyper Rare paga 31, una Ilustración Rara 9, una Rara 2. Lo que se corta es el
 * volumen, no la carta.
 *
 * SE VENDE POR ARRIBA: al vender n copias, las que se van son las de índice más
 * ALTO (las más baratas) y la última repetida que queda es la que se pagaría
 * entera. Consecuencia buscada: vender de una en una y vender de golpe dan
 * EXACTAMENTE el mismo dinero, así que no hay forma de sacarle más a la curva
 * troceando la venta, y la estimación que se pinta antes de vender coincide
 * siempre con lo que abona el servidor.
 *
 * OJO AL MERCADO: utils/mercado.ts paga `multiplicador × Σ SELL_PRICES` y usa
 * SELL_PRICES DIRECTAMENTE (precioDeVenta), no esta curva. No se ajusta solo.
 * Es deliberado —su calibrado y lo que pinta la pantalla del mercado salen de
 * ese precio plano— y no abre un agujero porque el tablón absorbe como mucho
 * unas pocas decenas de cartas al día. Está medido en scripts/sim-economia.mjs.
 */

/** Copias que nunca se venden: el álbum jamás se queda sin la carta. */
export const COPIAS_PROTEGIDAS = 1;

/** Fracción de SELL_PRICES a la que se aplana la curva. */
export const SUELO_COPIAS = 1 / 8;

/** Copias en las que el precio cae a la mitad (la nº 7 vale el 50%). */
export const SEMIVIDA_COPIAS = 6;

/** Primera copia que ya cobra el suelo. Sale de igualar factor(n) a SUELO. */
export const COPIA_SUELO = 1 + SEMIVIDA_COPIAS * (1 / SUELO_COPIAS - 1); // 43

/** Tarifa cuando la rareza no está en SELL_PRICES (mismo respaldo de siempre). */
const PRECIO_BASE_POR_DEFECTO = 10;

/**
 * Tarifa de una carta suelta: lo que paga su PRIMERA copia repetida, sin la
 * curva de copias. Es SELL_PRICES con el respaldo aplicado, y existe para que
 * nadie vuelva a escribir `SELL_PRICES[r] ?? 10` por su cuenta: utils/packLogic.ts
 * lo necesita para calcular cuánto vale un sobre antes de repartirlo, y si ese
 * respaldo se separase del de valorDeVenta, el sobre se calibraría contra un
 * precio que la tienda no paga.
 */
export function precioDeCartaSuelta(rareza: string | null | undefined): number {
  return SELL_PRICES[rareza ?? ""] ?? PRECIO_BASE_POR_DEFECTO;
}

/** Precio de la copia repetida nº `indice` (1 = la primera repetida). */
function precioDeCopia(base: number, indice: number): number {
  const factor = Math.max(SUELO_COPIAS, 1 / (1 + (Math.max(1, indice) - 1) / SEMIVIDA_COPIAS));
  // Redondeo a moneda entera y mínimo 1: una carta nunca se regala.
  return Math.max(1, Math.round(base * factor));
}

/**
 * ÚNICA fuente de verdad del dinero que produce vender repetidas. La usan
 * sellCardAction, sellAllDuplicatesAction, sellAllDuplicatesBulkAction,
 * sellPackDuplicates y la estimación que pinta la colección: si alguien calcula
 * el precio por su cuenta, el número que se enseña y el que se cobra se separan.
 *
 * @param rareza        rareza de la carta (la de la BD en el servidor).
 * @param copiasQueTengo copias en propiedad ANTES de vender.
 * @param copiasAVender  cuántas se venden; por defecto todas las repetidas.
 * @returns monedas totales, ya en entero.
 */
export function valorDeVenta(
  rareza: string | null | undefined,
  copiasQueTengo: number,
  copiasAVender?: number,
): number {
  const base = precioDeCartaSuelta(rareza);
  const repetidas = Math.max(0, Math.floor(Number(copiasQueTengo) || 0) - COPIAS_PROTEGIDAS);
  const pedidas = copiasAVender === undefined ? repetidas : Math.floor(Number(copiasAVender) || 0);
  const aVender = Math.min(repetidas, Math.max(0, pedidas));
  if (aVender === 0) return 0;

  // Se venden los índices [desde, hasta], los más altos del montón.
  const hasta = repetidas;
  const desde = repetidas - aVender + 1;

  // Tramo plano: por encima de COPIA_SUELO todas valen igual, así que se
  // multiplican en vez de recorrerlas. Sin esto, vaciar 400 repetidas de una
  // carta serían 400 vueltas de bucle por carta, en el servidor y en cada
  // repintado de la colección.
  const enSuelo = Math.max(0, hasta - Math.max(desde, COPIA_SUELO) + 1);
  let total = enSuelo * precioDeCopia(base, COPIA_SUELO);

  const tope = Math.min(hasta, COPIA_SUELO - 1);
  for (let i = desde; i <= tope; i++) total += precioDeCopia(base, i);

  return total;
}

